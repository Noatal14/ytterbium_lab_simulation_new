class PreliminaryResultError(ValueError):
    """A closed preliminary-check result registry is scientifically invalid."""

    def __init__(self, code: str):
        super().__init__(code)
        self.code = code


@dataclass(frozen=True)
class ValidatedPreliminaryResults:
    paths: tuple[str, ...]
    sha256: Mapping[str, str]
    summaries: Mapping[str, Mapping[str, Any]]
    evidence_sha256: str


def _canonical(value: object) -> bytes:
    return json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
        allow_nan=False,
    ).encode("utf-8")


def _sha(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _strict_json(path: Path, *, require_mapping: bool = True) -> Any:
    def pairs(rows):
        value = {}
        for key, child in rows:
            if key in value:
                raise PreliminaryResultError("malformed_json")
            value[key] = child
        return value

    try:
        value = json.loads(
            path.read_text(encoding="utf-8"),
            object_pairs_hook=pairs,
            parse_constant=lambda _value: (_ for _ in ()).throw(ValueError()),
        )
    except PreliminaryResultError:
        raise
    except Exception as exc:
        raise PreliminaryResultError("malformed_json") from exc
    if require_mapping and not isinstance(value, dict):
        raise PreliminaryResultError("malformed_json")
    return value


def _strict_json_bytes(raw: bytes, *, require_mapping: bool = True) -> Any:
    def pairs(rows):
        value = {}
        for key, child in rows:
            if key in value:
                raise ValueError("duplicate key")
            value[key] = child
        return value

    try:
        value = json.loads(
            raw.decode("utf-8", "strict"),
            object_pairs_hook=pairs,
            parse_constant=lambda _value: (_ for _ in ()).throw(ValueError()),
        )
    except Exception as exc:
        raise PreliminaryResultError("malformed_json") from exc
    if require_mapping and not isinstance(value, dict):
        raise PreliminaryResultError("malformed_json")
    return value


def _candidate_ids(selection: Mapping[str, Any], family: str) -> tuple[str, ...]:
    candidates = selection.get("candidates")
    if (
        set(selection) != {
            "kind", "family", "requested_candidate_count", "selected_candidate_count",
            "selection_pool_minimum_fraction", "parameter_bounds", "candidates",
        }
        or selection.get("kind") != "mot_3d_discovery_candidate_selection"
        or selection.get("family") != family
        or type(selection.get("requested_candidate_count")) is not int
        or selection["requested_candidate_count"] != EXPECTED_CANDIDATES_PER_FAMILY
        or type(selection.get("selected_candidate_count")) is not int
        or selection["selected_candidate_count"] != EXPECTED_CANDIDATES_PER_FAMILY
        or not isinstance(candidates, list)
        or len(candidates) != EXPECTED_CANDIDATES_PER_FAMILY
    ):
        raise PreliminaryResultError("selection_mismatch")
    identifiers = tuple(
        row.get("candidate_id") for row in candidates if isinstance(row, dict)
    )
    if (
        len(identifiers) != EXPECTED_CANDIDATES_PER_FAMILY
        or any(
            not isinstance(value, str) or CANDIDATE_ID.fullmatch(value) is None
            for value in identifiers
        )
        or len(set(identifiers)) != len(identifiers)
    ):
        raise PreliminaryResultError("selection_mismatch")
    return identifiers


def expected_paths(selections: Mapping[str, Mapping[str, Any]]) -> tuple[str, ...]:
    paths: set[str] = set()
    for family in FAMILIES:
        identifiers = _candidate_ids(selections[family], family)
        for worker in WORKERS:
            paths.add(
                f"preliminary_check/{family}/worker_{worker}/particle_selection.json"
            )
            for index, candidate_id in enumerate(identifiers):
                if index % len(WORKERS) != worker:
                    continue
                for seed in RECOIL_SEEDS:
                    stem = f"{candidate_id}_seed_{seed}"
                    paths.add(f"preliminary_check/{family}/worker_{worker}/{stem}.json")
                    paths.add(f"preliminary_check/{family}/worker_{worker}/{stem}.npz")
        paths.add(f"preliminary_check/{family}/merged/early_check_summary.json")
    if len(paths) != EXPECTED_RESULT_FILES:
        raise RuntimeError("closed preliminary-check registry is inconsistent")
    return tuple(sorted(paths))


def _finite_tree(value: object) -> bool:
    if isinstance(value, bool) or value is None or isinstance(value, str):
        return True
    if isinstance(value, int):
        return True
    if isinstance(value, float):
        return math.isfinite(value)
    if isinstance(value, list):
        return all(_finite_tree(child) for child in value)
    if isinstance(value, dict):
        return all(
            isinstance(key, str) and _finite_tree(child) for key, child in value.items()
        )
    return False


def _validate_materialized_preliminary_results(
    campaign: Path,
    manifest: Mapping[str, Any],
    *,
    source_campaign_path: str | None = None,
) -> ValidatedPreliminaryResults:
    """Validate the exact 152-file preliminary result registry.

    This path adapter is intended only for the already anchored remote campaign
    descriptor.  The transition receiver must first capture every allowlisted
    file with bounded, no-follow reads and re-attest those bytes before
    publication.  Scientific validation below never trusts summary-only state.
    """

    from workflow_api import mot_3d_workload as workload

    selected_design = workload.scientific_design(manifest, "preliminary_check")
    expected_count = (
        selected_design.input_ensembles * selected_design.particles_per_ensemble
    )
    frozen_keys = FROZEN_DESIGN_KEYS | set(workload.artifact_identity(manifest))
    campaign = Path(campaign)
    stage = manifest.get("stages", {}).get("preliminary_check", {})
    design = manifest.get("design", {})
    if (
        manifest.get("stage") != "preliminary_check"
        or stage.get("classification") != "candidate_selection_not_final_validation"
        or stage.get("input_role") != "preliminary_check"
        or design.get("screening_dt_s") != selected_design.dt_s
        or design.get("solver") != selected_design.solver
    ):
        raise PreliminaryResultError("design_mismatch")
    selections = {
        family: _strict_json(campaign / "selection" / "discovery" / f"{family}.json")
        for family in FAMILIES
    }
    paths = expected_paths(selections)
    actual = {
        path.relative_to(campaign).as_posix()
        for family in FAMILIES
        for path in (campaign / "preliminary_check" / family).rglob("*")
        if path.is_file() or path.is_symlink()
    }
    if actual != set(paths):
        raise PreliminaryResultError("artifact_registry_mismatch")

    summaries: dict[str, Mapping[str, Any]] = {}
    hashes: dict[str, str] = {}
    for relative in paths:
        path = campaign / relative
        if path.is_symlink() or not path.is_file():
            raise PreliminaryResultError("artifact_registry_mismatch")
        hashes[relative] = _sha(path)

    for family in FAMILIES:
        selection = selections[family]
        identifiers = _candidate_ids(selection, family)
        json_paths: list[Path] = []
        npz_paths: list[Path] = []
        particle_selections = []
        for worker in WORKERS:
            worker_root = campaign / "preliminary_check" / family / f"worker_{worker}"
            particle_selections.append(
                _strict_json(
                    worker_root / "particle_selection.json", require_mapping=False
                )
            )
            assigned = identifiers[worker :: len(WORKERS)]
            for candidate_id in assigned:
                for seed in RECOIL_SEEDS:
                    stem = f"{candidate_id}_seed_{seed}"
                    json_paths.append(worker_root / f"{stem}.json")
                    npz_paths.append(worker_root / f"{stem}.npz")
        if any(value != particle_selections[0] for value in particle_selections[1:]):
            raise PreliminaryResultError("particle_selection_mismatch")
        try:
            # This validator is needed only while inspecting remote scientific
            # outputs. Keep the HTTP server's import graph independent of studies.
            from studies.mot_3d.integrity import validate_artifact_registry

            records = validate_artifact_registry(
                json_paths,
                npz_paths,
                candidates=selection["candidates"],
                recoil_seeds=RECOIL_SEEDS,
                kind="mot_3d_early_independent_check_seed_result",
                family=family,
            )
        except Exception as exc:
            raise PreliminaryResultError("result_registry_invalid") from exc
        expected_design = None
        for record in records:
            if (
                set(record)
                != {
                    "kind",
                    "family",
                    "candidate_id",
                    "worker_index",
                    "recoil_seed",
                    "input_particle_count",
                    "usable_at_end_count",
                    "usable_ever_count",
                    "peak_usable_count",
                    "entered_capture_region_count",
                    "slow_inside_count",
                    "outcomes_path",
                    "outcomes_sha256",
                    "design",
                }
                or record["kind"] != "mot_3d_early_independent_check_seed_result"
                or record["family"] != family
                or record["candidate_id"] not in identifiers
                or not isinstance(record["worker_index"], int)
                or isinstance(record["worker_index"], bool)
                or record["worker_index"] not in WORKERS
                or not isinstance(record["recoil_seed"], int)
                or isinstance(record["recoil_seed"], bool)
                or record["recoil_seed"] not in RECOIL_SEEDS
                or not isinstance(record["input_particle_count"], int)
                or isinstance(record["input_particle_count"], bool)
                or record["input_particle_count"] != expected_count
                or identifiers.index(record["candidate_id"]) % 3
                != record["worker_index"]
                or any(
                    not isinstance(record[key], int)
                    or isinstance(record[key], bool)
                    or not 0 <= record[key] <= expected_count
                    for key in (
                        "usable_at_end_count",
                        "usable_ever_count",
                        "peak_usable_count",
                        "entered_capture_region_count",
                        "slow_inside_count",
                    )
                )
                or record["peak_usable_count"] < record["usable_at_end_count"]
                or record["slow_inside_count"] > record["entered_capture_region_count"]
            ):
                raise PreliminaryResultError("result_metadata_mismatch")
            current = record["design"]
            if expected_design is None:
                expected_design = current
            elif current != expected_design:
                raise PreliminaryResultError("design_mismatch")
            if (
                not isinstance(current, dict)
                or set(current) != frozen_keys
                or any(
                    current.get(key) != value
                    for key, value in workload.artifact_identity(manifest).items()
                )
                or (
                    source_campaign_path is not None
                    and current.get("campaign_manifest_path")
                    != str(PurePosixPath(source_campaign_path) / "campaign.json")
                )
                or (
                    source_campaign_path is not None
                    and current.get("selection_path")
                    != str(
                        PurePosixPath(source_campaign_path)
                        / "selection"
                        / "discovery"
                        / f"{family}.json"
                    )
                )
                or current.get("git_commit")
                != manifest.get("provenance", {}).get("git_commit")
                or current.get("physical_model_sha256")
                != manifest.get("provenance", {}).get("physical_model_sha256")
                or current.get("input_role") != "preliminary_check"
                or current.get("campaign_manifest_sha256")
                != _sha(campaign / "campaign.json")
                or current.get("input_role_sha256")
                != hashlib.sha256(
                    _canonical(manifest.get("input_roles", {}).get("preliminary_check"))
                ).hexdigest()
                or current.get("particle_selection_sha256")
                != hashlib.sha256(_canonical(particle_selections[0])).hexdigest()
                or current.get("dt_s") != selected_design.dt_s
                or current.get("t_max_s") != selected_design.t_max_s
                or current.get("solver") != selected_design.solver
                or current.get("particles_per_ensemble")
                != selected_design.particles_per_ensemble
                or current.get("selection_seed") != selected_design.selection_seed
                or current.get("selection_sha256")
                != _sha(campaign / "selection" / "discovery" / f"{family}.json")
            ):
                raise PreliminaryResultError("design_mismatch")
            npz_path = next(
                path
                for path in npz_paths
                if path.stem == f"{record['candidate_id']}_seed_{record['recoil_seed']}"
            )
            with np.load(npz_path, allow_pickle=False) as archive:
                if set(archive.files) != {
                    "usable_at_end",
                    "usable_ever",
                    "ensemble_ids",
                }:
                    raise PreliminaryResultError("result_archive_invalid")
                usable = np.asarray(archive["usable_at_end"])
                ever = np.asarray(archive["usable_ever"])
                groups = np.asarray(archive["ensemble_ids"])
                if (
                    usable.shape != (expected_count,)
                    or ever.shape != (expected_count,)
                    or groups.shape != (expected_count,)
                    or usable.dtype != np.bool_
                    or ever.dtype != np.bool_
                    or not np.issubdtype(groups.dtype, np.integer)
                    or set(np.unique(groups).tolist()) != {0, 1, 2, 3}
                    or any(
                        int(np.sum(groups == index))
                        != selected_design.particles_per_ensemble
                        for index in range(selected_design.input_ensembles)
                    )
                    or int(usable.sum()) != record["usable_at_end_count"]
                    or int(ever.sum()) != record["usable_ever_count"]
                    or np.any(usable & ~ever)
                ):
                    raise PreliminaryResultError("result_archive_invalid")

        summary_path = (
            campaign
            / "preliminary_check"
            / family
            / "merged"
            / "early_check_summary.json"
        )
        summary = _strict_json(summary_path)
        if (
            summary.get("kind") != "merged_mot_3d_early_independent_check"
            or summary.get("family") != family
            or summary.get("candidate_count") != EXPECTED_CANDIDATES_PER_FAMILY
            or summary.get("particle_count") != expected_count
            or summary.get("ensemble_file_indices") != [16, 17, 18, 19]
            or summary.get("recoil_seed_count") != 3
            or summary.get("bootstrap_replicates") != EXPECTED_BOOTSTRAP_REPLICATES
            or summary.get("bootstrap_seed") != EXPECTED_BOOTSTRAP_SEED
            or summary.get("multiplicity_method") != EXPECTED_MULTIPLICITY_METHOD
            or summary.get("selection_sha256")
            != _sha(campaign / "selection" / "discovery" / f"{family}.json")
            or summary.get("design") != expected_design
            or not _finite_tree(summary)
        ):
            raise PreliminaryResultError("summary_mismatch")
        ranked = summary.get("ranked_candidates")
        if (
            not isinstance(ranked, list)
            or len(ranked) != EXPECTED_CANDIDATES_PER_FAMILY
            or {row.get("candidate_id") for row in ranked if isinstance(row, dict)}
            != set(identifiers)
            or summary.get("lcb_leader_candidate_id") not in identifiers
        ):
            raise PreliminaryResultError("summary_mismatch")
        summaries[family] = summary

        # The summary is a scientific decision input, not merely a convenient
        # report.  Recompute it with the canonical merger so a self-consistent
        # but fabricated summary cannot influence refinement selection.
        from studies.mot_3d.preliminary.merge import merge

        with tempfile.TemporaryDirectory(
            prefix="mot3d-preliminary-verify-"
        ) as temporary:
            output = Path(temporary)
            with contextlib.redirect_stdout(io.StringIO()):
                merge(
                    Namespace(
                        selection=str(
                            campaign / "selection" / "discovery" / f"{family}.json"
                        ),
                        input_root=str(campaign / "preliminary_check" / family),
                        output_dir=str(output),
                        bootstrap_replicates=EXPECTED_BOOTSTRAP_REPLICATES,
                        bootstrap_seed=EXPECTED_BOOTSTRAP_SEED,
                    )
                )
            recomputed = _strict_json(output / "early_check_summary.json")
        if recomputed != summary:
            raise PreliminaryResultError("summary_mismatch")

    evidence = hashlib.sha256(_canonical(hashes)).hexdigest()
    return ValidatedPreliminaryResults(paths, hashes, summaries, evidence)


def _validate_npz_container(raw: bytes, *, max_member_bytes: int = 128 * 1024) -> None:
    """Reject oversized/foreign members before NumPy sees the archive."""

    if (
        type(max_member_bytes) is not int
        or not 0 < max_member_bytes <= 2 * 1024 * 1024
        or not 0 < len(raw) <= 2 * 1024 * 1024
    ):
        raise PreliminaryResultError("result_archive_invalid")
    try:
        with zipfile.ZipFile(io.BytesIO(raw)) as archive:
            rows = archive.infolist()
            if len(rows) != 3 or {row.filename for row in rows} != {
                "usable_at_end.npy",
                "usable_ever.npy",
                "ensemble_ids.npy",
            }:
                raise PreliminaryResultError("result_archive_invalid")
            for row in rows:
                if (
                    row.is_dir()
                    or row.file_size <= 0
                    or row.file_size > max_member_bytes
                    or row.compress_size <= 0
                    or row.compress_size > max_member_bytes
                    or row.flag_bits & 0x1
                    or row.compress_type
                    not in {zipfile.ZIP_STORED, zipfile.ZIP_DEFLATED}
                ):
                    raise PreliminaryResultError("result_archive_invalid")
    except PreliminaryResultError:
        raise
    except Exception as exc:
        raise PreliminaryResultError("result_archive_invalid") from exc


def validate_npz_container_bytes(
    raw: bytes, *, max_member_bytes: int = 128 * 1024
) -> None:
    """Public shared preflight for the canonical three-member outcome archive."""
    _validate_npz_container(raw, max_member_bytes=max_member_bytes)


def _outcome_reference_matches(reference: object, *, campaign_absolute_path: str,
                               project_directory: str, artifact: str) -> bool:
    """Match only the two canonical renderer spellings of one frozen artifact."""
    if any(type(value) is not str or not value or "\\" in value
           for value in (campaign_absolute_path, project_directory, artifact)):
        return False
    campaign = PurePosixPath(campaign_absolute_path)
    project = PurePosixPath(project_directory)
    suffix = PurePosixPath(artifact)
    if (not campaign.is_absolute() or not project.is_absolute()
            or str(campaign) != campaign_absolute_path or str(project) != project_directory
            or project not in campaign.parents or suffix.is_absolute()
            or str(suffix) != artifact
            or any(part in {".", ".."} for path in (campaign, project, suffix) for part in path.parts)):
        return False
    absolute = campaign / suffix
    try:
        relative = absolute.relative_to(project)
    except ValueError:
        return False
    return type(reference) is str and reference in {str(absolute), str(relative)}


def _frozen_input_absolute_path(value: object, project: PurePosixPath) -> PurePosixPath:
    """Authenticate a frozen POSIX identity without changing its serialized form."""
    if type(value) is not str or not value or "\\" in value or "\x00" in value:
        raise PreliminaryResultError("particle_selection_mismatch")
    path = PurePosixPath(value)
    if str(path) != value or any(part in {"", ".", ".."} for part in path.parts):
        raise PreliminaryResultError("particle_selection_mismatch")
    if not path.is_absolute():
        if not path.parts or path.parts[0] != "data":
            raise PreliminaryResultError("particle_selection_mismatch")
        path = project / path
    if project not in path.parents:
        raise PreliminaryResultError("particle_selection_mismatch")
    return path


def validate_frozen_role_records(
    records: object,
    *,
    project_directory: str,
    expected_zeeman_seeds: tuple[int, ...],
    source_git_commit: str,
    acceptance_provenance: Mapping[str, Any] | None = None,
) -> list[Mapping[str, Any]]:
    """Validate the immutable input-role ledger shared by later 3D stages."""

    project = PurePosixPath(project_directory)
    if (
        type(project_directory) is not str
        or not project.is_absolute()
        or str(project) != project_directory
        or any(part in {"", ".", ".."} for part in project.parts[1:])
        or type(expected_zeeman_seeds) is not tuple
        or any(type(seed) is not int or seed < 0 for seed in expected_zeeman_seeds)
        or len(set(expected_zeeman_seeds)) != len(expected_zeeman_seeds)
        or type(source_git_commit) is not str
        or HEX40.fullmatch(source_git_commit) is None
        or not isinstance(records, list)
        or len(records) != len(expected_zeeman_seeds)
    ):
        raise PreliminaryResultError("particle_selection_mismatch")
    validated = []
    seen_mot_seeds: set[int] = set()
    for index, record in enumerate(records):
        if not isinstance(record, Mapping) or set(record) != FROZEN_ROLE_KEYS:
            raise PreliminaryResultError("particle_selection_mismatch")
        count = record["n_survivors"]
        path = record["path"]
        metadata_path = record["metadata_path"]
        array_path = _frozen_input_absolute_path(path, project)
        metadata = _frozen_input_absolute_path(metadata_path, project)
        mot_seed = record["mot_seed"]
        if (
            type(count) is not int
            or not 1 <= count <= 50_000
            or type(record["zeeman_seed"]) is not int
            or record["zeeman_seed"] != expected_zeeman_seeds[index]
            or type(mot_seed) is not int
            or mot_seed < 0
            or mot_seed in seen_mot_seeds
            or array_path is None
            or metadata is None
            or not array_path.is_absolute()
            or not metadata.is_absolute()
            or any(part in {"", ".", ".."} for part in array_path.parts[1:])
            or any(part in {"", ".", ".."} for part in metadata.parts[1:])
            or array_path.parts[: len(project.parts)] != project.parts
            or metadata.parts[: len(project.parts)] != project.parts
            or array_path.suffix != ".npy"
            or metadata != array_path.with_suffix(".json")
            or type(record["sha256"]) is not str
            or HEX64.fullmatch(record["sha256"]) is None
            or type(record["metadata_sha256"]) is not str
            or HEX64.fullmatch(record["metadata_sha256"]) is None
            or record["shape"] != [count, 6]
            or record["dtype"] != "float64"
            or record["source_git_commit"] != source_git_commit
            or not isinstance(record["source_design"], Mapping)
            or not isinstance(record["source_parameters"], Mapping)
        ):
            raise PreliminaryResultError("particle_selection_mismatch")
        from workflow_api.acceptance_profile import (
            assert_acceptance_path,
            assert_scientific_source,
        )

        if acceptance_provenance is not None:
            if record["source_design"].get("acceptance") != acceptance_provenance:
                raise PreliminaryResultError("particle_selection_mismatch")
            try:
                assert_acceptance_path(str(array_path), project_directory)
                assert_acceptance_path(str(metadata), project_directory)
            except ValueError as error:
                raise PreliminaryResultError("particle_selection_mismatch") from error
        else:
            try:
                assert_scientific_source(record)
            except ValueError as error:
                raise PreliminaryResultError("particle_selection_mismatch") from error
        seen_mot_seeds.add(mot_seed)
        validated.append(record)
    return validated


def expected_selection_particle_provenance(
    manifest: Mapping[str, Any],
    *,
    project_directory: str,
    input_role: str,
    input_ensembles: int,
    particles_per_ensemble: int,
    selection_seed: int,
    expected_zeeman_seeds: tuple[int, ...],
) -> list[dict[str, Any]]:
    """Derive canonical selection provenance without reopening input arrays.

    Random indices depend only on the frozen survivor count and Zeeman seed.
    The receiver separately attests the manifest, array and metadata hashes;
    this pure derivation therefore avoids a second mutable pathname read.
    """

    records = manifest.get("input_roles", {}).get(input_role)
    if not isinstance(records, list) or len(records) != input_ensembles:
        raise PreliminaryResultError("particle_selection_mismatch")
    from workflow_api.mot_3d_workload import policy

    acceptance = policy(manifest)
    project = PurePosixPath(project_directory)
    if (
        not project.is_absolute()
        or str(project) != project_directory
        or len(project.parts) != 4
        or project.parts[1] != "home"
        or project.parts[3]
        != (
            "ytterbium_lab_simulation_ui_acceptance"
            if acceptance
            else "ytterbium_lab_simulation_new"
        )
    ):
        raise PreliminaryResultError("particle_selection_mismatch")
    provenance = []
    seen_mot_seeds = set()
    upstream_pairs = {
        row.get("zeeman_seed"): row.get("mot_seed")
        for row in manifest.get("upstream_2d_campaign", {}).get("sealed_seed_pairs", [])
        if isinstance(row, Mapping)
    }
    if (
        type(input_role) is not str
        or type(input_ensembles) is not int
        or input_ensembles <= 0
        or type(particles_per_ensemble) is not int
        or particles_per_ensemble <= 0
        or type(selection_seed) is not int
        or selection_seed < 0
        or type(expected_zeeman_seeds) is not tuple
        or len(expected_zeeman_seeds) != input_ensembles
        or any(type(value) is not int or value < 0 for value in expected_zeeman_seeds)
    ):
        raise PreliminaryResultError("particle_selection_mismatch")
    for ensemble_id, record in enumerate(records):
        if not isinstance(record, Mapping) or set(record) != FROZEN_ROLE_KEYS:
            raise PreliminaryResultError("particle_selection_mismatch")
        count = record["n_survivors"]
        zeeman_seed = record["zeeman_seed"]
        mot_seed = record["mot_seed"]
        path = record["path"]
        metadata_path = record["metadata_path"]
        digest = record["sha256"]
        absolute_path = _frozen_input_absolute_path(path, project)
        absolute_metadata = _frozen_input_absolute_path(metadata_path, project)
        if (
            not isinstance(count, int)
            or isinstance(count, bool)
            or count < particles_per_ensemble
            or count > 50_000
            or not isinstance(zeeman_seed, int)
            or isinstance(zeeman_seed, bool)
            or zeeman_seed != expected_zeeman_seeds[ensemble_id]
            or not isinstance(mot_seed, int)
            or isinstance(mot_seed, bool)
            or mot_seed < 0
            or mot_seed in seen_mot_seeds
            or not isinstance(path, str)
            or not isinstance(metadata_path, str)
            or PurePosixPath(path).parent != PurePosixPath(metadata_path).parent
            or PurePosixPath(path).suffix != ".npy"
            or PurePosixPath(metadata_path) != PurePosixPath(path).with_suffix(".json")
            or str(PurePosixPath(path)) != path
            or str(PurePosixPath(metadata_path)) != metadata_path
            or not isinstance(digest, str)
            or HEX64.fullmatch(digest) is None
            or not isinstance(record["metadata_sha256"], str)
            or HEX64.fullmatch(record["metadata_sha256"]) is None
            or record["shape"] != [count, 6]
            or record["dtype"] != "float64"
            or not isinstance(record["source_git_commit"], str)
            or HEX40.fullmatch(record["source_git_commit"]) is None
            or not isinstance(record["source_design"], Mapping)
            or not isinstance(record["source_parameters"], Mapping)
            or (upstream_pairs and upstream_pairs.get(zeeman_seed) != mot_seed)
        ):
            raise PreliminaryResultError("particle_selection_mismatch")
        from workflow_api.acceptance_profile import (
            assert_acceptance_path,
            assert_scientific_source,
        )

        try:
            if acceptance is not None:
                if record["source_design"].get("acceptance") != acceptance.provenance():
                    raise ValueError(
                        "Acceptance frozen source design has different lineage."
                    )
                assert_acceptance_path(str(absolute_path), project_directory)
                assert_acceptance_path(str(absolute_metadata), project_directory)
            else:
                assert_scientific_source(record)
        except ValueError as error:
            raise PreliminaryResultError("particle_selection_mismatch") from error
        seen_mot_seeds.add(mot_seed)
        rng = np.random.default_rng(
            np.random.SeedSequence([selection_seed, zeeman_seed])
        )
        indices = np.sort(
            rng.choice(
                count,
                size=particles_per_ensemble,
                replace=False,
            )
        )
        provenance.append(
            {
                "ensemble_id": ensemble_id,
                "file": path,
                "array_sha256": digest,
                "zeeman_seed": zeeman_seed,
                "mot_seed": mot_seed,
                "available_count": count,
                "selected_indices": indices.tolist(),
            }
        )
    return provenance


def expected_preliminary_particle_selection(
    manifest: Mapping[str, Any], *, project_directory: str
) -> list[dict[str, Any]]:
    from workflow_api.mot_3d_workload import scientific_design

    selected_design = scientific_design(manifest, "preliminary_check")
    return expected_selection_particle_provenance(
        manifest,
        project_directory=project_directory,
        input_role="preliminary_check",
        input_ensembles=selected_design.input_ensembles,
        particles_per_ensemble=selected_design.particles_per_ensemble,
        selection_seed=selected_design.selection_seed,
        expected_zeeman_seeds=tuple(range(3031, 3035)),
    )


def validate_preliminary_result_bytes(
    *,
    manifest_bytes: bytes,
    selection_bytes: Mapping[str, bytes],
    result_files: Mapping[str, bytes],
    expected_particle_selection: object,
    campaign_absolute_path: str,
    project_directory: str,
) -> ValidatedPreliminaryResults:
    """Validate captured immutable bytes, independent of remote pathnames.

    The caller owns the descriptor-bound capture and must pass the exact closed
    registry.  Materialization occurs only in a private temporary directory so
    canonical analysis helpers cannot escape to attacker-controlled paths.
    """

    if (
        not isinstance(manifest_bytes, bytes)
        or not 0 < len(manifest_bytes) <= 2 * 1024 * 1024
        or not isinstance(selection_bytes, Mapping)
        or set(selection_bytes) != set(FAMILIES)
        or any(
            not isinstance(raw, bytes) or not 0 < len(raw) <= 2 * 1024 * 1024
            for raw in selection_bytes.values()
        )
        or not isinstance(result_files, Mapping)
        or not isinstance(campaign_absolute_path, str)
        or not isinstance(project_directory, str)
    ):
        raise PreliminaryResultError("artifact_registry_mismatch")
    try:
        manifest = _strict_json_bytes(manifest_bytes)
        selections = {
            family: _strict_json_bytes(selection_bytes[family]) for family in FAMILIES
        }
    except Exception as exc:
        raise PreliminaryResultError("malformed_json") from exc
    from workflow_api.mot_3d_workload import policy

    acceptance = policy(manifest)
    expected_root = PurePosixPath(project_directory)
    campaign_path = PurePosixPath(campaign_absolute_path)
    if (
        not expected_root.is_absolute()
        or str(expected_root) != project_directory
        or len(expected_root.parts) != 4
        or expected_root.parts[1] != "home"
        or expected_root.parts[3]
        != (
            "ytterbium_lab_simulation_ui_acceptance"
            if acceptance
            else "ytterbium_lab_simulation_new"
        )
        or not campaign_path.is_absolute()
        or campaign_path
        != expected_root
        / "data"
        / "optimization"
        / "mot_3d"
        / ("ui_acceptance" if acceptance else "")
        / campaign_path.name
        or str(campaign_path) != campaign_absolute_path
        or campaign_path.name != manifest.get("name")
    ):
        raise PreliminaryResultError("artifact_registry_mismatch")
    expected = frozenset(expected_paths(selections))
    if set(result_files) != expected:
        raise PreliminaryResultError("artifact_registry_mismatch")
    for name, raw in result_files.items():
        if not isinstance(raw, bytes) or not 0 < len(raw) <= 2 * 1024 * 1024:
            raise PreliminaryResultError("artifact_registry_mismatch")
        if name.endswith(".npz"):
            _validate_npz_container(raw)

    with tempfile.TemporaryDirectory(prefix="mot3d-preliminary-captured-") as temporary:
        campaign = Path(temporary) / "campaign"
        campaign.mkdir()
        (campaign / "campaign.json").write_bytes(manifest_bytes)
        for family in FAMILIES:
            target = campaign / "selection" / "discovery" / f"{family}.json"
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(selection_bytes[family])
        for name, raw in result_files.items():
            target = campaign.joinpath(*Path(name).parts)
            target.parent.mkdir(parents=True, exist_ok=True)
            if name.endswith("particle_selection.json"):
                try:
                    captured = _strict_json_bytes(raw, require_mapping=False)
                except Exception as exc:
                    raise PreliminaryResultError("malformed_json") from exc
                if captured != expected_particle_selection:
                    raise PreliminaryResultError("particle_selection_mismatch")
            if (
                name.endswith(".json")
                and "worker_" in name
                and not name.endswith("particle_selection.json")
            ):
                try:
                    record = _strict_json_bytes(raw)
                    suffix = PurePosixPath(name).with_suffix(".npz").as_posix()
                    if not _outcome_reference_matches(
                        record.get("outcomes_path"), campaign_absolute_path=campaign_absolute_path,
                        project_directory=project_directory, artifact=suffix,
                    ):
                        raise PreliminaryResultError("result_metadata_mismatch")
                    record["outcomes_path"] = str(campaign / suffix)
                    raw = json.dumps(record, indent=2, allow_nan=False).encode() + b"\n"
                except PreliminaryResultError:
                    raise
                except Exception as exc:
                    raise PreliminaryResultError("malformed_json") from exc
            target.write_bytes(raw)
        validated = _validate_materialized_preliminary_results(
            campaign, manifest, source_campaign_path=campaign_absolute_path
        )
    hashes = {
        name: hashlib.sha256(raw).hexdigest() for name, raw in result_files.items()
    }
    evidence = hashlib.sha256(_canonical(hashes)).hexdigest()
    return ValidatedPreliminaryResults(
        tuple(sorted(result_files)), hashes, validated.summaries, evidence
    )
