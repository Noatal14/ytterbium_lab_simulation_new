class ZeusSmokeSubmissionCoordinator:
    """HTTP-facing preview/confirm coordinator for exactly one smoke PBS."""

    def __init__(self, repository_root: Path, ssh_executable: Path, git_executable: Path, *, clock=time.time, token_factory=None, transport_factory=None):
        self.root = repository_root.resolve(strict=True); self.ssh = ssh_executable.resolve(strict=True); self.git = git_executable.resolve(strict=True)
        self.clock = clock; self.transport_factory = transport_factory or (lambda profile: PinnedSshSmokeSubmissionTransport(self.root, self.ssh, profile))
        self._previews = PreviewRegistry[_Pending](clock=clock, token_factory=token_factory)
        self._confirm_lock = threading.Lock()
        if not self.git.is_file() or not os.access(self.git,os.X_OK) or self.root in self.git.parents:
            raise ValueError("The trusted Git executable is unavailable.")

    def _revision(self) -> tuple[str, bool]:
        env={"PATH":str(self.git.parent),"HOME":str(Path.home()),"LC_ALL":"C","GIT_CONFIG_NOSYSTEM":"1","GIT_OPTIONAL_LOCKS":"0","GIT_TERMINAL_PROMPT":"0","GIT_PAGER":"cat"}
        def run(args: list[str]) -> bytes:
            try: result=subprocess.run([str(self.git),*args],cwd=self.root,env=env,stdin=subprocess.DEVNULL,stdout=subprocess.PIPE,stderr=subprocess.PIPE,shell=False,close_fds=True,timeout=10,check=False)
            except subprocess.TimeoutExpired: raise ZeusSubmissionError("local_repository_unavailable") from None
            if result.returncode or len(result.stdout)>1024*1024 or len(result.stderr)>65536: raise ZeusSubmissionError("local_repository_unavailable")
            return result.stdout
        try:
            commit=run(["rev-parse","--verify","HEAD^{commit}"]).decode("ascii").strip()
            status=run(["status","--porcelain=v1","-z","--untracked-files=all"])
        except UnicodeError: raise ZeusSubmissionError("local_repository_unavailable") from None
        if not COMMIT_RE.fullmatch(commit): raise ZeusSubmissionError("local_repository_unavailable")
        return commit,self._safe_untracked_status(status)

    def _safe_untracked_status(self, raw: bytes) -> bool:
        """Allow generated data only; reject untracked import/native code."""
        return RepositoryRevisionService._safe_untracked_status(self.root, raw)

    def _plan(self, campaign_id: str) -> tuple[Path, dict[str, object], str, dict[str, str], str, str]:
        entry=build_registry(self.root).get(campaign_id)
        if entry is None or entry.family!="mot_2d": raise ZeusSubmissionError("campaign_not_found")
        try: manifest=_load_manifest(entry.manifest)
        except ZeusPreparationError as error: raise ZeusSubmissionError("campaign_not_canonical") from error
        campaign=entry.manifest.parent
        if manifest.get("stage")!="smoke": raise ZeusSubmissionError("campaign_not_smoke")
        try:
            artifact_plan = CampaignArtifactPlanner(self.root).plan(campaign)
            selected, commit = artifact_plan.files, artifact_plan.commit
            canonical=render_campaign_files(manifest, campaign, self.root)
        except (ZeusPreparationError, ValueError, OSError) as error:
            raise ZeusSubmissionError("campaign_not_canonical") from error
        manifest_path=campaign/"campaign.json"; job=campaign/"jobs/01_smoke.pbs"
        if manifest_path.read_bytes()!=canonical["campaign.json"] or job.read_bytes()!=canonical["jobs/01_smoke.pbs"]:
            raise ZeusSubmissionError("campaign_not_canonical")
        files={path:item[1] for path,item in selected.items()}
        campaign_relative=campaign.relative_to(self.root).as_posix(); job_relative=job.relative_to(self.root).as_posix()
        key=hashlib.sha256(json.dumps({"campaign":campaign_relative,"commit":commit,"manifest":files[campaign_relative+"/campaign.json"],"pbs":files[job_relative]},sort_keys=True,separators=(",",":")).encode()).hexdigest()
        return campaign,manifest,commit,files,job_relative,key

    def preview(self, request: Mapping[str, object], *, session_id: str) -> dict[str, object]:
        if set(request)!={"campaign_id","username","project_directory"} or not isinstance(request.get("campaign_id"),str): raise ZeusSubmissionError("request_invalid")
        try: profile=ZeusProfile.parse({"username":request.get("username"),"project_directory":request.get("project_directory")})
        except ValueError as error: raise ZeusSubmissionError("profile_invalid") from error
        campaign_id=str(request["campaign_id"]); campaign,manifest,commit,files,job,key=self._plan(campaign_id)
        local_commit,clean=self._revision()
        if not clean or local_commit!=commit: raise ZeusSubmissionError("local_checkout_mismatch")
        transport=self.transport_factory(profile); state=transport.inspect(files=files,campaign=campaign.relative_to(self.root).as_posix(),job_file=job,commit=commit,submission_key=key)
        if state.branch is None: raise ZeusSubmissionError("remote_response_invalid")
        if state.status=="ambiguous": raise ZeusSubmissionError("submission_outcome_unknown")
        if state.status=="submitted": raise ZeusSubmissionError("already_submitted")
        nonce=secrets.token_hex(16); expires=self.clock()+TOKEN_LIFETIME_SECONDS
        pending=_Pending(session_id,campaign_id,campaign,profile,commit,files,job,key,nonce,expires)
        try:
            token = self._previews.add(
                pending,
                expires_at=expires,
                capacity=MAX_PENDING_PREVIEWS,
            )
        except OverflowError as error:
            raise ZeusSubmissionError("too_many_pending_previews") from error
        name=manifest.get("name") if isinstance(manifest.get("name"),str) else campaign.name
        s0_values=manifest.get("s0_values")
        if not isinstance(s0_values,list) or not s0_values: raise ZeusSubmissionError("campaign_not_canonical")
        return {"preview_token":token,"expires_in_seconds":TOKEN_LIFETIME_SECONDS,"campaign":{"id":campaign_id,"name":name,"path":campaign.relative_to(self.root).as_posix(),"git_commit":commit,"s0_values":s0_values},"stage":{"id":"smoke","label":"Smoke check","purpose":"Validate the prepared 2D-MOT campaign before longer optimization stages."},"job":{"file":"jobs/01_smoke.pbs","kind":"job" if len(s0_values)==1 else "array","task_count":len(s0_values),"queue":"zeus_combined_q","cores_per_task":1,"memory_per_task_bytes":68719476736,"walltime_seconds":1200},"remote":{"host":ZEUS_HOST,"project_directory":profile.project_directory,"commit":commit,"branch":state.branch,"dirty":False},"inputs":{"verified_count":72,"status":"ready"},"effects":{"submit_smoke":True,"submit_later_stages":False,"modify_files":False},"later_stages_locked":True}

    def confirm(self, request: Mapping[str, object], *, session_id: str) -> dict[str, object]:
        if set(request)!={"preview_token"} or not isinstance(request.get("preview_token"),str): raise ZeusSubmissionError("request_invalid")
        token=str(request["preview_token"])
        with self._confirm_lock:
            record = self._previews.get(token)
            pending = record.value if record is not None else None
            if pending is None or not secrets.compare_digest(pending.session_id,session_id): raise ZeusSubmissionError("confirmation_invalid")
            if pending.result is not None: return dict(pending.result)
            if pending.terminal_error is not None: raise ZeusSubmissionError(pending.terminal_error)
            if self.clock()>pending.expires_at:
                self._previews.pop(token)
                raise ZeusSubmissionError("confirmation_expired")
            campaign,_,commit,files,job,key=self._plan(pending.campaign_id); local_commit,clean=self._revision()
            if campaign!=pending.campaign_root or not clean or local_commit!=commit or commit!=pending.commit or files!=pending.files or job!=pending.job_file or key!=pending.submission_key: raise ZeusSubmissionError("local_files_changed")
            transport=self.transport_factory(pending.profile)
            try:
                state=transport.submit(files=files,campaign=campaign.relative_to(self.root).as_posix(),job_file=job,commit=commit,submission_key=key,nonce=pending.nonce)
            except ZeusSubmissionError as error:
                if error.code in {
                    "submission_outcome_unknown",
                    "already_submitted",
                    "smoke_already_started",
                }:
                    self._previews.replace(token, replace(pending, terminal_error=error.code))
                raise
            if state.status!="submitted" or state.job_id is None or state.submitted_unix_s is None:
                self._previews.replace(token, replace(pending, terminal_error="submission_outcome_unknown"))
                raise ZeusSubmissionError("submission_outcome_unknown")
            if state.nonce!=pending.nonce:
                self._previews.replace(token, replace(pending, terminal_error="already_submitted"))
                raise ZeusSubmissionError("already_submitted")
            try: submitted_at=datetime.fromtimestamp(state.submitted_unix_s,tz=timezone.utc).isoformat()
            except (OverflowError,OSError,ValueError):
                self._previews.replace(token, replace(pending, terminal_error="submission_outcome_unknown"))
                raise ZeusSubmissionError("submission_outcome_unknown") from None
            result={"status":"submitted","campaign_id":pending.campaign_id,"stage":"smoke","job_id":state.job_id,"submitted_at":submitted_at,"later_stages_locked":True}
            # Publish the terminal result before releasing _confirm_lock so
            # concurrent retries cannot invoke the transport a second time.
            self._previews.replace(token, replace(pending, result=result))
            return dict(result)
