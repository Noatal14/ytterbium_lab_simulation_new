class PinnedSshSmokeSubmissionTransport:
    """Fixed SSH adapter for the embedded smoke-submission receiver."""

    def __init__(self, repository_root: Path, ssh_executable: Path, profile: ZeusProfile, *, timeout: float = 45):
        self.root = repository_root.resolve(strict=True)
        self.ssh = ssh_executable.resolve(strict=True)
        self.profile = profile
        self.timeout = timeout
        if not self.ssh.is_file() or not os.access(self.ssh, os.X_OK) or self.root in self.ssh.parents:
            raise ValueError("The trusted SSH executable is unavailable.")

    def _request(self, operation: str, **payload: object) -> SubmissionRemoteState:
        if operation not in {"inspect", "submit"}:
            raise ZeusSubmissionError("remote_response_invalid")
        integrity_code = "submission_outcome_unknown" if operation == "submit" else "remote_response_invalid"
        encoded = base64.urlsafe_b64encode(json.dumps(payload, sort_keys=True, separators=(",", ":")).encode()).decode("ascii")
        script = base64.urlsafe_b64encode(_REMOTE_SCRIPT.encode()).decode("ascii")
        wrapper = "import base64,sys;payload=sys.argv[1];sys.argv=sys.argv[1:];exec(base64.urlsafe_b64decode(payload).decode('utf-8'))"
        remote = shlex.join(("python3", "-c", wrapper, script, operation, self.profile.username, self.profile.project_directory, encoded))
        argv = [str(self.ssh), "-F", "none", "-T", "-o", "BatchMode=yes", "-o", "PasswordAuthentication=no", "-o", "KbdInteractiveAuthentication=no", "-o", "NumberOfPasswordPrompts=0", "-o", "ConnectTimeout=8", "-o", "ConnectionAttempts=1", "-o", "StrictHostKeyChecking=yes", "-o", "ForwardAgent=no", "-o", "ClearAllForwardings=yes", "-o", "PermitLocalCommand=no", "-o", "ProxyCommand=none", "-o", "ProxyJump=none", "-o", "KnownHostsCommand=none", "-o", "CanonicalizeHostname=no", "-o", "LogLevel=ERROR", f"{self.profile.username}@{ZEUS_HOST}", remote]
        env = {"PATH": str(self.ssh.parent), "HOME": str(Path.home()), "LC_ALL": "C"}
        if os.environ.get("SSH_AUTH_SOCK"): env["SSH_AUTH_SOCK"] = os.environ["SSH_AUTH_SOCK"]
        try:
            result = subprocess.run(argv, cwd=self.root, env=env, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.PIPE, shell=False, close_fds=True, timeout=self.timeout, check=False)
        except subprocess.TimeoutExpired:
            raise ZeusSubmissionError("submission_outcome_unknown" if operation == "submit" else "zeus_timeout") from None
        if len(result.stdout) > MAX_REMOTE_OUTPUT or len(result.stderr) > MAX_REMOTE_OUTPUT:
            raise ZeusSubmissionError(integrity_code)
        stderr = result.stderr.decode("utf-8", "replace").lower()
        if result.returncode and not result.stdout:
            if "host key verification failed" in stderr: raise ZeusSubmissionError("zeus_host_key_untrusted")
            if "permission denied" in stderr: raise ZeusSubmissionError("zeus_authentication_required")
            if "could not resolve hostname" in stderr or "connection refused" in stderr: raise ZeusSubmissionError("zeus_unreachable")
        # Once a submit receiver may have reached qsub, stderr makes the
        # outcome untrustworthy even when stdout resembles a success record.
        if stderr:
            raise ZeusSubmissionError(integrity_code)
        try: response = json.loads(result.stdout.decode("utf-8", "strict"))
        except (UnicodeError, json.JSONDecodeError):
            raise ZeusSubmissionError(integrity_code) from None
        if not isinstance(response, dict): raise ZeusSubmissionError(integrity_code)
        if "error" in response:
            code = response.get("error")
            allowed = {"invalid_request", "remote_project_missing", "remote_preparation_invalid", "submission_record_invalid", "submission_busy", "submission_ambiguous", "smoke_already_started"}
            if operation == "submit" and code in {"submission_ambiguous", "submission_record_invalid"}:
                raise ZeusSubmissionError("submission_outcome_unknown")
            if code not in allowed:
                raise ZeusSubmissionError(integrity_code)
            raise ZeusSubmissionError(str(code))
        if result.returncode != 0:
            raise ZeusSubmissionError(integrity_code)
        status, job_id, nonce = response.get("status"), response.get("job_id"), response.get("nonce")
        if status not in {"eligible", "submitted", "ambiguous"}: raise ZeusSubmissionError(integrity_code)
        expected_keys = {
            ("inspect", "eligible"): {"status", "branch"},
            ("inspect", "ambiguous"): {"status", "nonce", "branch"},
            ("inspect", "submitted"): {"status", "job_id", "nonce", "submitted_unix_s", "branch"},
            ("submit", "submitted"): {"status", "job_id", "nonce", "submitted_unix_s"},
        }.get((operation, status))
        if expected_keys is None or set(response) != expected_keys:
            raise ZeusSubmissionError(integrity_code)
        if status == "submitted" and (not isinstance(job_id, str) or not JOB_PARENT_RE.fullmatch(job_id)):
            raise ZeusSubmissionError(integrity_code)
        if status in {"ambiguous", "submitted"} and (not isinstance(nonce, str) or not NONCE_RE.fullmatch(nonce)):
            raise ZeusSubmissionError(integrity_code)
        branch = response.get("branch")
        if operation == "inspect" and (not isinstance(branch, str) or not branch or len(branch) > 256 or not branch.isprintable()):
            raise ZeusSubmissionError(integrity_code)
        submitted = response.get("submitted_unix_s")
        if status == "submitted" and (not isinstance(submitted, int) or not 0 <= submitted <= 253402300799):
            raise ZeusSubmissionError(integrity_code)
        return SubmissionRemoteState(status, job_id if isinstance(job_id, str) else None, nonce if isinstance(nonce, str) else None, branch if isinstance(branch, str) else None, submitted if isinstance(submitted, int) else None)

    def inspect(self, **kwargs: object) -> SubmissionRemoteState:
        return self._request("inspect", **kwargs, nonce=None)

    def submit(self, **kwargs: object) -> SubmissionRemoteState:
        return self._request("submit", **kwargs)


