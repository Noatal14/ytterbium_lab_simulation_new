"""Generate the exact browser workload contract from the reviewed test policy."""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from workflow_api.acceptance_profile import load_acceptance_profile


def render():
    profile = load_acceptance_profile()
    policy = json.loads((ROOT/'workflow_api/specifications/ui_acceptance_v1.json').read_text(encoding='utf-8'))
    spec = json.loads((ROOT/'workflow_api/specifications/mot_2d_v1.json').read_text(encoding='utf-8'))
    workload = policy['mot_2d']
    spec['design']['screen_trials_per_worker'] = workload['stages']['screen']['trials_per_worker']
    spec['design']['refine_trials_per_worker'] = workload['stages']['refine']['trials_per_worker']
    for stage, row in spec['stages'].items():
        stage_policy = workload['stages'][stage]
        row['cores_per_task'] = stage_policy['ncpus']
        row['memory_per_task_bytes'] = stage_policy['memory_gb'] * 1024**3
        row['walltime_seconds'] = stage_policy['walltime_seconds']
    spec['stages']['refine']['cumulative_trial_targets'] = workload['refinement_cumulative_targets']
    return ('// Generated by scripts/generate_ui_acceptance_catalog.py; do not edit.\n'
            f'export const UI_ACCEPTANCE_IDENTITY = {json.dumps(profile.provenance(), indent=2, sort_keys=True)} as const;\n'
            f'export const UI_ACCEPTANCE_POLICY = {json.dumps(policy, indent=2, sort_keys=True)} as const;\n'
            f'export const MOT_2D_ACCEPTANCE_SPECIFICATION = {json.dumps(spec, indent=2, sort_keys=True)} as const;\n')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT/'ui/src/generated/uiAcceptance.v1.ts'
    expected = render()
    if args.check:
        if not output.exists() or output.read_text(encoding='utf-8') != expected:
            raise SystemExit('UI acceptance contract is stale.')
    else:
        output.write_text(expected, encoding='utf-8')

if __name__ == '__main__': main()
