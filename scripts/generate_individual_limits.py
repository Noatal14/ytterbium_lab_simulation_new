"""Regenerate the UI projection of the individual capacity authority."""
import json
from pathlib import Path
from workflow_api.individual_limits import particle_policy


def render() -> str:
    return ("// Generated by scripts/generate_individual_limits.py; do not edit.\n"
            + "export const INDIVIDUAL_PARTICLE_POLICY = "
            + json.dumps(particle_policy(), indent=2, sort_keys=True)
            + " as const;\n")


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1]
    (root / "ui/src/generated/individualLimits.v1.ts").write_text(render())
